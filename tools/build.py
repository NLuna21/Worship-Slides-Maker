"""Offline build. Reads data/songs.xlsx -> js/songs-data.js (the copy used when index.html is opened by double-click),
then bundles everything into one self-contained dist/worship-slide-builder.html.
Needs:  pip install openpyxl      Usage:  python3 tools/build.py
(Not needed on a website: the hosted app reads data/songs.xlsx directly.)"""
import json,re,pathlib
from openpyxl import load_workbook
R=pathlib.Path(__file__).resolve().parent.parent
ws=load_workbook(R/'data/songs.xlsx',read_only=True)['Song Database']
clean=lambda v:'' if v in (None,'N/A') else str(v).strip()
songs=[]
for i,r in enumerate(ws.iter_rows(values_only=True)):
    if i==0 or not r or not r[0]: continue   # row 1 = column headings
    r=list(r)+['']*(17-len(r))
    secs=[str(c).replace('­','').replace('\r','').strip() for c in r[16:] if c is not None and str(c).strip()]
    if secs: songs.append({'t':str(r[0]).strip(),'w':clean(r[2]),'k':clean(r[5]),'s':clean(r[11]),'ty':clean(r[12]),'secs':secs})
(R/'js/songs-data.js').write_text('// GENERATED by tools/build.py from data/songs.xlsx - edit the Excel file, not this one.\nconst SEED='+json.dumps(songs,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
html=(R/'index.html').read_text(encoding='utf-8')
html=html.replace('<link rel="stylesheet" href="css/styles.css">','<style>'+(R/'css/styles.css').read_text(encoding='utf-8')+'</style>')
html=re.sub(r'<script src="(js/[^"]+)"></script>',lambda m:'<script>'+(R/m.group(1)).read_text(encoding='utf-8').replace('</script','<\\/script')+'</script>',html)
(R/'dist').mkdir(exist_ok=True);(R/'dist/worship-slide-builder.html').write_text(html,encoding='utf-8')
print('built',len(songs),'songs from data/songs.xlsx -> dist/worship-slide-builder.html',len(html)//1024,'KB')
